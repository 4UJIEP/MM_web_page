
export interface Course {
  /** Уникальный идентификатор курса */
  id: string;
  
  /** Название курса (например, "Математика") */
  title: string;
  
  /** Текст бейджа (например, "1-11 классы") */
  badge: string;
  
  /** Цвет фона бейджа (например, "#ABF5CC") */
  badgeColor: string;
  
  /** Продолжительность занятия (например, "2 часа") */
  duration: string;
  
  /** Уровень сложности (например, "Немало") */
  difficulty: string;
  
  /** Количество занятий в курсе */
  lessonsCount: number;
  
  /** Путь к изображению курса */
  image: string;
}